// Reglas para números con unidad en español: "24 pulgadas", "3 anios",
// "Hasta 18 horas", "Hasta 10 min (carga media)", "Hasta 160°".
const REGLAS_VALOR_EN = [
  [/^(\d+(?:[.,]\d+)?) pulgadas?$/i, (_, n) => `${n} inches`],
  [/^(\d+) a(?:n|ñ)ios?$/i, (_, n) => `${n} ${Number(n) === 1 ? "year" : "years"}`],
  [/^Hasta (\d+) horas$/i, (_, n) => `Up to ${n} hours`],
  [/^Hasta (\d+) min \(carga media\)$/i, (_, n) => `Up to ${n} min (medium load)`],
  [/^Hasta (\d+)°$/i, (_, n) => `Up to ${n}°`],
];

function valorTextoEn(texto) {
  if (VALORES_EN[texto]) return VALORES_EN[texto];
  for (const [regla, aEn] of REGLAS_VALOR_EN) {
    const m = regla.exec(texto);
    if (m) return aEn(...m);
  }
  return texto;
}

export function nombreSpec(clave = "", idioma = "es") {
  if (idioma === "en" && ETIQUETAS_EN[clave]) return ETIQUETAS_EN[clave];
  const palabras = String(clave)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => {
      const base = w.toLowerCase();
      if (idioma === "en" && PALABRAS_EN[base]) return PALABRAS_EN[base];
      if (PALABRAS[base]) return PALABRAS[base];
      // Siglas que ya vienen en mayúsculas (L3, M2, LCD…) se respetan.
      return w.length > 1 && w === w.toUpperCase() ? w : base;
    });
  const texto = palabras.join(" ");
  return texto.charAt(0).toUpperCase() + texto.slice(1);
}

export function valorSpec(valor, { si = "Sí", no = "No", idioma = "es" } = {}) {
  const texto = (v) => (idioma === "en" ? valorTextoEn(String(v)) : String(v));
  if (typeof valor === "boolean") return valor ? si : no;
  if (Array.isArray(valor)) return valor.map(texto).join(", ");
  return texto(valor);
}
