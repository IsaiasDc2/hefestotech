const useIdiomaStore = create((set) => ({
  idioma: (() => {
    try {
      const v = localStorage.getItem("ht-idioma");
      return v === "en" ? "en" : "es";
    } catch {
      return "es";
    }
  })(),
  setIdioma: (idioma) => {
    try {
      localStorage.setItem("ht-idioma", idioma);
    } catch {
      // Storage bloqueado (modo privado): el idioma vale solo en esta visita.
    }
    document.documentElement.lang = idioma === "en" ? "en" : "es-AR";
    set({ idioma });
  },
}));

